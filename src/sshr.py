"""Opt-in SSHR estimator using separate labelled and unlabelled fitting pools.

Every call fits a fresh SSHC model and applies the audited resampling core.
Existing unlabelled observations selected for pseudo-labelling remain distinct
from vectors generated by the within-cluster SMOTE fallback. Author-code
behavior remains unverified; see ``docs/SSHR_METHOD_DECISIONS.md``.

The three-input ``fit_resample`` interface requires an explicit training-only
call. Conventional imbalanced-learn pipelines do not automatically supply its
separate unlabelled pool. This estimator fits no preprocessing or classifier
and has no hidden-label input.
"""
from __future__ import annotations

from copy import deepcopy
import json
from numbers import Integral
from typing import Any

from sklearn.base import BaseEstimator

from ._validation import finite_real, positive_integer
from .sshr_clustering import SSHC
from .sshr_resampling import SSHRResamplingError, SSHRResamplingResult, resample_from_clusters


class SSHR(BaseEstimator):
    """Semi-supervised resampling with an explicit, independently fitted pool.

    ``minority_label`` fixes the source-domain class identity when supplied;
    otherwise SSHC infers it from observed counts and requires an explicit
    identity for tied counts. Defaults and source conflicts are inherited from
    the audited SSHC/SSHR modules rather than selected from held-out scores.

    Successful fitted attributes include ``clustering_``, ``result_``, input
    provenance indices, synthesis lineage, and JSON diagnostics. Validation
    failures clear all fitted state. Diagnosed preliminary-cleaning failures
    preserve only fresh failure ``diagnostics_`` and re-raise the original error.
    """

    def __init__(
        self,
        minority_label: Any = None,
        mu: float = 0.5,
        objective_mode: str = "paper_printed",
        prune_scope: str = "majority_only",
        tol: float = 1e-8,
        max_split_rounds: int = 100,
        max_refine_iter: int = 100,
        delta: float = 0.1,
        removal_fraction: float = 0.3,
        k_neighbors: int = 5,
        random_state: int = 42,
        smote_pool_policy: str = "observed_and_selected",
    ) -> None:
        self.minority_label = minority_label
        self.mu = mu
        self.objective_mode = objective_mode
        self.prune_scope = prune_scope
        self.tol = tol
        self.max_split_rounds = max_split_rounds
        self.max_refine_iter = max_refine_iter
        self.delta = delta
        self.removal_fraction = removal_fraction
        self.k_neighbors = k_neighbors
        self.random_state = random_state
        self.smote_pool_policy = smote_pool_policy

    def _clear_fitted_state(self) -> None:
        for name in list(vars(self)):
            if name.endswith("_"):
                delattr(self, name)

    def _validate_resampling_parameters(self) -> None:
        """Reject invalid resampling settings before any costly clustering."""
        delta = finite_real(self.delta, "delta")
        fraction = finite_real(self.removal_fraction, "removal_fraction")
        if not 0 <= delta <= 1:
            raise ValueError("delta must lie in [0, 1].")
        if not 0 <= fraction <= 1:
            raise ValueError("removal_fraction must lie in [0, 1].")
        positive_integer(self.k_neighbors, "k_neighbors")
        if (isinstance(self.random_state, bool)
                or not isinstance(self.random_state, Integral)
                or not 0 <= self.random_state < 2**32):
            raise ValueError("random_state must be an integer in [0, 2**32).")
        if (not isinstance(self.smote_pool_policy, str)
                or self.smote_pool_policy not in {"observed_and_selected", "observed_only"}):
            raise ValueError("smote_pool_policy must be 'observed_and_selected' or 'observed_only'.")

    def fit_resample(self, X_labeled: Any, y_labeled: Any,
                     X_unlabeled: Any = None) -> tuple[Any, Any]:
        """Fit on the supplied training pools and return independent arrays.

        The caller is responsible for training/test separation and source
        categorical-feature metadata. Numerical storage cannot establish that
        one-hot coordinates represent continuous features. Held-out features
        must never be included in ``X_unlabeled``.
        """
        self._clear_fitted_state()
        try:
            self._validate_resampling_parameters()
            clustering = SSHC(
                minority_label=self.minority_label,
                mu=self.mu,
                objective_mode=self.objective_mode,
                prune_scope=self.prune_scope,
                tol=self.tol,
                max_split_rounds=self.max_split_rounds,
                max_refine_iter=self.max_refine_iter,
            ).fit(X_labeled, y_labeled, X_unlabeled)
            result = resample_from_clusters(
                X_labeled, y_labeled, X_unlabeled, clustering,
                delta=self.delta,
                removal_fraction=self.removal_fraction,
                k_neighbors=self.k_neighbors,
                random_state=self.random_state,
                smote_pool_policy=self.smote_pool_policy,
            )
            # Validate before publishing learned attributes. A malformed
            # diagnostic must never leave a partially fitted estimator behind.
            if not isinstance(result.diagnostics, dict):
                raise ValueError("SSHR diagnostics must be a finite JSON-compatible dictionary.")
            json.dumps(result.diagnostics, allow_nan=False)
            json.dumps(result.row_lineage, allow_nan=False)
            stored = SSHRResamplingResult(
                result.X_resampled.copy(), result.y_resampled.copy(),
                result.retained_labeled_indices.copy(), result.selected_unlabeled_indices.copy(),
                result.synthetic_samples.copy(), deepcopy(result.row_lineage), deepcopy(result.diagnostics),
            )
            self.clustering_ = clustering
            self.result_ = stored
            self.retained_labeled_indices_ = stored.retained_labeled_indices.copy()
            self.selected_unlabeled_indices_ = stored.selected_unlabeled_indices.copy()
            self.synthetic_samples_ = stored.synthetic_samples.copy()
            self.row_lineage_ = deepcopy(stored.row_lineage)
            self.diagnostics_ = deepcopy(stored.diagnostics)
            self.classes_ = clustering.classes_.copy()
            self.minority_label_ = clustering.minority_label_
            self.majority_label_ = clustering.majority_label_
            self.n_features_in_ = clustering.n_features_in_
            return stored.X_resampled.copy(), stored.y_resampled.copy()
        except SSHRResamplingError as exc:
            self._clear_fitted_state()
            failure = deepcopy(exc.diagnostics)
            if not isinstance(failure, dict):
                raise ValueError("SSHR failure diagnostics must be a finite JSON-compatible dictionary.") from exc
            failure["estimator_failure"] = {"exception_type": type(exc).__name__, "message": str(exc)}
            try:
                json.dumps(failure, allow_nan=False)
            except (ValueError, TypeError) as diagnostics_error:
                raise ValueError("SSHR failure diagnostics must be finite JSON-compatible data.") from diagnostics_error
            self.diagnostics_ = failure
            raise
        except Exception:
            self._clear_fitted_state()
            raise


__all__ = ["SSHR"]
